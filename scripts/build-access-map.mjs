import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const themes=JSON.parse(await fs.readFile(path.join(root,'location-themes.json'),'utf8'));
const esc=s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('"','&quot;');
const green='#609126',silom='#1e6555',blue='#285da1',ink='#24342f',muted='#52615c';
const text=(x,y,value,{size=22,fill=ink,anchor='start',weight=400}={})=>'<text x="'+x+'" y="'+y+'" font-family="Arial,sans-serif" font-size="'+size+'" font-weight="'+weight+'" text-anchor="'+anchor+'" fill="'+fill+'">'+esc(value)+'</text>';
const line=(d,color,width=10,dash='')=>'<path d="'+d+'" fill="none" stroke="'+color+'" stroke-width="'+width+'" stroke-linecap="round" stroke-linejoin="round"'+(dash?' stroke-dasharray="'+dash+'"':'')+'/>';
const station=(x,y,c,r=10)=>'<circle cx="'+x+'" cy="'+y+'" r="'+r+'" fill="#fff" stroke="'+c+'" stroke-width="5"/>';
function mall(slug,x,y,w,number,lines){
 const t=themes[slug];return '<g><rect x="'+x+'" y="'+y+'" width="'+w+'" height="85" rx="8" fill="'+t.paper+'" stroke="'+t.accent+'" stroke-width="2"/><circle cx="'+(x+24)+'" cy="'+(y+25)+'" r="15" fill="'+t.ink+'"/>'+text(x+24,y+31,number,{size:18,fill:'#fff',anchor:'middle',weight:700})+lines.map((s,i)=>text(x+48,y+33+i*27,s,{size:22,fill:t.ink,weight:700})).join('')+'</g>';
}
let svg='<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1200 665" role="img" aria-labelledby="map-title map-desc"><title id="map-title">Five Bangkok shopping centres and their rail connections</title><desc id="map-desc">BTS Sukhumvit line: Siam, Chit Lom, Phloen Chit, Nana, Asok. Siam Center and Siam Paragon connect to Siam; CentralWorld to Chit Lom; Central Embassy to Phloen Chit; Terminal 21 Asok to Asok and MRT Sukhumvit. The BTS Silom line changes at Siam. The MRT Blue line connects at Asok / Sukhumvit. Diagram not to scale.</desc><rect width="1200" height="665" fill="#fff"/>';
svg+=text(30,37,'Central Bangkok · rail connections',{size:28,weight:700});
for(const [x,color,label]of [[30,green,'BTS Sukhumvit'],[330,silom,'BTS Silom'],[600,blue,'MRT Blue']])svg+=line('M'+x+' 80 h46',color,8)+text(x+60,88,label,{size:22});
svg+=line('M895 80 h46',muted,3,'7 7')+text(955,88,'Walk / link',{size:22});
svg+=mall('siam-center',30,135,150,2,['Siam','Center']);
svg+=mall('siam-paragon',185,135,150,4,['Siam','Paragon']);
svg+=mall('centralworld',380,135,210,1,['CentralWorld']);
svg+=mall('central-embassy',610,135,220,5,['Central','Embassy']);
svg+=mall('terminal-21-asok',930,135,240,3,['Terminal 21','Asok']);
svg+=line('M105 220 v25 h155 v-25 M182 245 V315 L220 404',muted,3,'7 7');
svg+=line('M485 220 V330 H460 V404',muted,3,'7 7');
svg+=line('M720 220 V330 H690 V404',muted,3,'7 7');
svg+=line('M1050 220 V270 H1000 V330 L1025 405',muted,3,'7 7');
svg+=line('M80 350 L220 420 V590',silom);
svg+=line('M1040 285 V605',blue);
svg+=line('M120 420 H1165',green);
svg+=station(80,350,silom,8)+text(80,304,'National',{size:21,anchor:'middle'})+text(80,330,'Stadium',{size:21,anchor:'middle'});
svg+=station(220,590,silom,8)+text(246,599,'Ratchadamri',{size:22});
svg+=station(220,420,silom,16)+station(220,420,green,9);
svg+=text(195,464,'Siam',{anchor:'end',weight:700})+text(195,493,'Change BTS lines',{size:20,anchor:'end',fill:muted});
for(const [x,name]of [[460,'Chit Lom'],[690,'Phloen Chit'],[860,'Nana']])svg+=station(x,420,green)+text(x,464,name,{anchor:'middle',weight:700});
svg+=station(1040,420,blue,16)+station(1040,420,green,9);
svg+=text(1065,464,'Asok (BTS)',{weight:700})+text(1065,494,'Sukhumvit',{weight:700})+text(1065,520,'(MRT)',{size:20,weight:700})+text(1065,552,'Change trains',{size:18,fill:muted});
svg+=text(30,650,'Selected stations only. Diagram not to scale.',{size:21,fill:muted});
svg+='</svg>';
await fs.writeFile(path.join(root,'assets/bangkok-access-map.svg'),svg);
